function generateExecutiveAudit(
  businessName: string,
  targetAudience: string
): AuditResult {
  const cleanBusiness = businessName.trim();
  const cleanAudience = targetAudience.trim();

  // Deterministic seed generation
  let hash = 0;
  const combined = `${cleanBusiness.toLowerCase()}::${cleanAudience.toLowerCase()}`;
  for (let i = 0; i < combined.length; i++) {
    hash = (hash << 5) - hash + combined.charCodeAt(i);
    hash |= 0;
  }
  const positiveHash = Math.abs(hash);

  // Growth Score between 74 and 96
  const baseScore = 74 + (positiveHash % 23);
  const growthScore = Math.min(97, Math.max(68, baseScore));

  const scoreTier =
    growthScore >= 90
      ? "Tier-1 Elite Velocity"
      : growthScore >= 82
      ? "High-Yield Growth Potential"
      : "Moderate Optimization Tier";

  const percentile = 80 + (positiveHash % 17);

  const subMetrics: SubMetric[] = [
    {
      label: "Frictionless AI Lead Capture",
      score: Math.min(99, growthScore + ((positiveHash % 7) - 3)),
      delta: "+28% vs Industry Benchmark",
    },
    {
      label: "ICP Message-Market Resonance",
      score: Math.min(98, growthScore - ((positiveHash % 9) - 4)),
      delta: "+34% Conversion Probability",
    },
    {
      label: "Autonomous Pipeline Velocity",
      score: Math.min(96, growthScore + ((positiveHash % 6) - 2)),
      delta: "2.4x Shorter Sales Cycle",
    },
  ];

  const opportunities: Opportunity[] = [
    {
      id: "opp-1",
      title: "Real-Time Conversational AI Qualification Gate",
      impactBadge: "Critical Impact",
      impactType: "critical",
      category: "Funnel Friction & Triage",
      potentialGain: "+38% Inbound Pipeline",
      description: `Replace generic static forms with an intelligent triage assistant that immediately scores and qualifies ${cleanAudience} against ${cleanBusiness}'s ideal deal criteria in under 45 seconds.`,
    },
    {
      id: "opp-2",
      title: "Hyper-Personalized Multi-Touch AI Nurture Tracks",
      impactBadge: "High Leverage",
      impactType: "high",
      category: "Automated Re-Engagement",
      potentialGain: "+26% Lead-to-Meeting Rate",
      description: `Deploy behavioral trigger micro-sequences tailored specifically to the pain points of ${cleanAudience}, removing cognitive drop-off and addressing executive objections prior to sales contact.`,
    },
    {
      id: "opp-3",
      title: "Zero-Click Predictive Intent Routing & Instant Booking",
      impactBadge: "Rapid Win",
      impactType: "growth",
      category: "Pipeline Velocity",
      potentialGain: "+41% Same-Day Demos",
      description: `Eliminate back-and-forth friction by auto-routing high-scoring ${cleanAudience} prospects directly into ${cleanBusiness}'s tier-1 calendar slots with custom pre-briefings generated by AI.`,
    },
  ];

  const leadMagnetHook: LeadMagnetHook = {
    framework: "The Executive ROI Blueprint",
    headline: `The 2026 ${cleanBusiness} Growth Dossier: How ${cleanAudience} Unlocks 3.4x Pipeline Velocity Without Increasing Ad Spend`,
    subheadline: `A high-conviction, data-backed operational teardown built exclusively for ${cleanAudience}.`,
    bullets: [
      `The 3 hidden funnel choke points costing ${cleanBusiness} qualified prospects every quarter.`,
      `The proprietary automated triage matrix that converts passive ${cleanAudience} visitors into confirmed discovery calls.`,
      `Exact plug-and-play AI prompt sequences to automate 70% of inbound prospect qualification this month.`,
    ],
    callToAction: "Download The Executive Dossier & Implementation Checklist →",
    suggestedFormat: "Interactive 7-Page Executive Brief + Calculator",
  };

  return {
    businessName: cleanBusiness,
    targetAudience: cleanAudience,
    growthScore,
    scoreTier,
    percentileRank: `Top ${100 - percentile}% of peers`,
    subMetrics,
    opportunities,
    leadMagnetHook,
    auditTimestamp: "Generated Just Now",
  };
}


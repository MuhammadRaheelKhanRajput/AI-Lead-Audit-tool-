function ScoreRing({ score }: { score: number }) {
  const radius = 54;
  const circumference = 2 * Math.PI * radius;
  const strokeDashoffset = circumference - (score / 100) * circumference;

  const colorConfig =
    score >= 88
      ? {
          stroke: "stroke-emerald-400",
          glow: "from-emerald-500/20 to-teal-500/0",
          textColor: "text-emerald-400",
          badgeBg: "bg-emerald-500/10 text-emerald-300 border-emerald-500/20",
        }
      : score >= 78
      ? {
          stroke: "stroke-indigo-400",
          glow: "from-indigo-500/20 to-violet-500/0",
          textColor: "text-indigo-400",
          badgeBg: "bg-indigo-500/10 text-indigo-300 border-indigo-500/20",
        }
      : {
          stroke: "stroke-amber-400",
          glow: "from-amber-500/20 to-orange-500/0",
          textColor: "text-amber-400",
          badgeBg: "bg-amber-500/10 text-amber-300 border-amber-500/20",
        };

  return (
    <div className="relative flex flex-col items-center justify-center">
      <div className="relative w-44 h-44 flex items-center justify-center">
        {/* Glow halo */}
        <div
          className={`absolute inset-4 rounded-full bg-gradient-to-tr ${colorConfig.glow} blur-xl`}
        />

        <svg className="w-full h-full -rotate-90 transform" viewBox="0 0 130 130">
          <circle
            cx="65"
            cy="65"
            r={radius}
            fill="none"
            stroke="rgba(255, 255, 255, 0.07)"
            strokeWidth="9"
          />
          <circle
            cx="65"
            cy="65"
            r={radius}
            fill="none"
            className={`${colorConfig.stroke} animate-gauge`}
            strokeWidth="9"
            strokeLinecap="round"
            strokeDasharray={circumference}
            strokeDashoffset={strokeDashoffset}
            style={{
              transition: "stroke-dashoffset 1.4s cubic-bezier(0.16, 1, 0.3, 1)",
            }}
          />
        </svg>

        <div className="absolute inset-0 flex flex-col items-center justify-center text-center">
          <span className="text-5xl font-black tracking-tight text-white font-mono">
            {score}
          </span>
          <span className="text-[11px] font-semibold uppercase tracking-widest text-zinc-400 mt-0.5">
            Out of 100
          </span>
        </div>
      </div>
    </div>
  );
}

